USE EMASSAI;

CREATE TABLE IF NOT EXISTS AGENT_MGMT (
	AGENT_ID		VARCHAR(256) 	NOT NULL    COMMENT 'AGENT ID',
	CLIENT_IP		VARCHAR(256)	NULL        COMMENT 'CLIENT IP',
	LAST_STATUS_DT	DATETIME    	NULL        COMMENT '최종 상태 요청 시간',
	USER_ID			VARCHAR(256)	NULL        COMMENT 'USER ID',
	STATUS			VARCHAR(1)		NULL        COMMENT 'CONNECTION STATUS',
	PRIMARY KEY (AGENT_ID)
) ENGINE=INNODB DEFAULT CHARSET=UTF8MB3 COLLATE=UTF8MB3_GENERAL_CI COMMENT='AGENT 등록 목록';
CREATE INDEX IF NOT EXISTS AGENT_MGMT_USER_ID_IDX USING BTREE ON EMASSAI.AGENT_MGMT (USER_ID);


CREATE TABLE IF NOT EXISTS AGENT_POLICY (
	AGENT_ID		VARCHAR(256) 	NOT NULL COMMENT 'AGENT ID',
	CONF_ID			VARCHAR(256)	NOT NULL COMMENT 'CONF ID',
	CONF_NAME		VARCHAR(256)	NULL     COMMENT 'CONF NAME',
	CATEGORY		VARCHAR(256)	NULL     COMMENT '설정 카테고리',
	CONF_VAL		LONGTEXT		NULL     COMMENT 'CONF VALUE',
	DEF_CONF_VAL	LONGTEXT		NULL     COMMENT 'DEFAULT CONF VALUE',
	PRIMARY KEY (AGENT_ID, CONF_ID)
) ENGINE=INNODB DEFAULT CHARSET=UTF8MB3 COLLATE=UTF8MB3_GENERAL_CI COMMENT='AGENT POLICY CONFIG';


CREATE TABLE IF NOT EXISTS AGENT_PAC(
	PAC_ID          INT AUTO_INCREMENT,
	PAC_DESC		VARCHAR(256) 	NULL     COMMENT 'PAC 설명',
	PAC_VAL			LONGTEXT		NULL     COMMENT 'PAC FUNCTION',
	PAC_USED		VARCHAR(1)      NULL     COMMENT 'PAC USED (ONLY 1ROW Y)',
	CREATE_DT 		DATETIME 		NULL     COMMENT '등록 시간',
	CREATE_USER		VARCHAR(256)	NULL     COMMENT '등록 운용자',
	UPDATE_DT 		DATETIME 		NULL     COMMENT '수정 시간',
	UPDATE_USER		VARCHAR(256)	NULL     COMMENT '수정 운용자',
	PRIMARY KEY (PAC_ID)
) ENGINE=INNODB DEFAULT CHARSET=UTF8MB3 COLLATE=UTF8MB3_GENERAL_CI COMMENT='AGENT PAC CONFIG';


CREATE TABLE IF NOT EXISTS AGENT_SERVICE (
	HOST			VARCHAR(256) 	NOT NULL COMMENT 'HOST',
	SERVICECD		VARCHAR(1)		NOT NULL COMMENT 'SERVICE CODE',
  PRIMARY KEY (HOST)
) ENGINE=INNODB DEFAULT CHARSET=UTF8MB3 COLLATE=UTF8MB3_GENERAL_CI COMMENT='AGENT POLICY PAC SERVICE';

